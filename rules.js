const cnt = (r, t) => (t.match(r) || []).length;
const has = (r, t) => { r.lastIndex = 0; return r.test(t); };

export function classify(text) {
  const t = text.toLowerCase();
  const threats = Object.keys(TRX).filter(k => has(TRX[k], t));
  // "200 метрів" — це відстань, а не втрати
  if (threats.includes('Втрати / евакуація') && /(?:200|300)\s*(?:м$|м[ .,]|метр|кілом|килом)/iu.test(t) && !/поранен|ранен|евак|эвак|вакуац|сот[иі]й|сотих|сотого/iu.test(t))
    threats.splice(threats.indexOf('Втрати / евакуація'), 1);
  let cat = 'noise';
  if (threats.length || has(RX.critx, t)) cat = 'crit';
  else if (has(RX.log, t) && cnt(RX.log, t) >= cnt(RX.tact, t)) cat = 'log';
  else if (has(RX.tact, t)) cat = 'tact';
  else if (has(RX.coord, t)) cat = 'coord';
  else if (has(RX.noise, t) || t.replace(/[^а-яіїєґa-z]/giu, '').length < 12) cat = 'noise';
  else cat = 'tact';
  return { cat, threats };
}

const esc = s => s.replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

// Підсвічування сутностей: загроза / позивний / число-час-координата
export function highlight(text, callsigns = []) {
  const marks = [];
  const add = (r, cls) => { r.lastIndex = 0; let m; while ((m = r.exec(text))) { if (m[0].length && !(cls === 'e-thr' && /^[23]00$/.test(m[0]) && /^\s*(?:м|метр|кілом|килом)/iu.test(text.slice(m.index + 3)))) marks.push([m.index, m.index + m[0].length, cls]); else r.lastIndex++; } };
  add(RX.crit, 'e-thr');
  if (callsigns.length) add(rx(callsigns.map(c => c.toLowerCase().replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))), 'e-call');
  add(RX.coord, 'e-loc');
  add(NUMRX, 'e-num');
  marks.sort((a, b) => a[0] - b[0] || b[1] - a[1]);
  let out = '', pos = 0;
  for (const [s, e, c] of marks) {
    if (s < pos) continue;
    out += esc(text.slice(pos, s)) + `<b class="${c}">` + esc(text.slice(s, e)) + '</b>';
    pos = e;
  }
  return out + esc(text.slice(pos));
}
